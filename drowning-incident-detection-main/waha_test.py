"""WAHA (WhatsApp HTTP API) Test & Diagnostics Utility.

Run this script from terminal:
    python waha_test.py
Or with custom arguments:
    python waha_test.py --to 919876543210 --url http://localhost:3000
"""

import argparse
import base64
import glob
import os
import sys
from pathlib import Path

# Ensure UTF-8 output on Windows consoles
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

import requests

# Try importing local settings
try:
    import settings
    DEFAULT_PHONE = getattr(settings, "WAHA_PHONE_NUMBER", "")
    DEFAULT_URL = getattr(settings, "WAHA_BASE_URL", "http://localhost:3000")
    DEFAULT_SESSION = getattr(settings, "WAHA_SESSION", "default")
    DEFAULT_KEY = getattr(settings, "WAHA_API_KEY", "")
except Exception:
    DEFAULT_PHONE = ""
    DEFAULT_URL = "http://localhost:3000"
    DEFAULT_SESSION = "default"
    DEFAULT_KEY = ""


def check_status(base_url, session, api_key=""):
    print(f"\n[1/3] Checking WAHA connection at {base_url}...")
    headers = {}
    if api_key:
        headers["X-Api-Key"] = api_key

    try:
        # Check sessions list
        resp = requests.get(f"{base_url}/api/sessions", headers=headers, timeout=5)
        if resp.status_code != 200:
            print(f"[FAIL] WAHA responded with HTTP {resp.status_code}: {resp.text}")
            return False, None

        sessions = resp.json()
        print(f"[OK]   Connected to WAHA! Found {len(sessions)} active session(s).")

        # Find specific session
        matched = next((s for s in sessions if s.get("name") == session), None)
        if not matched:
            print(f"[WARN] Session '{session}' not found.")
            print(f"       Open {base_url}/dashboard in your browser and create a session.")
            return False, None

        status = matched.get("status", "UNKNOWN")
        print(f"[INFO] Session '{session}' status: {status}")

        if status != "WORKING":
            print(f"\n[ACTION REQUIRED] Session status is '{status}'.")
            print(f"  * Open the dashboard: {base_url}/dashboard")
            print(f"  * Or scan the QR Code image on your screen: qr_code.png")
            return False, status

        print(f"[OK]   WhatsApp session '{session}' is authenticated and READY!")
        return True, status

    except requests.exceptions.ConnectionError:
        print(f"[FAIL] Cannot reach WAHA at {base_url}.")
        print("       Make sure Docker is running and you started the WAHA container:")
        print("       docker run -d --name waha -p 3000:3000 -v waha_sessions:/app/.sessions devlikeapro/waha")
        return False, None
    except Exception as exc:
        print(f"[FAIL] Error checking status: {exc}")
        return False, None


def send_test_alert(base_url, session, phone, api_key=""):
    print(f"\n[2/3] Preparing test WhatsApp alert for {phone}...")
    import re
    digits = re.sub(r"\D", "", phone)
    if digits.startswith("00"):
        digits = digits[2:]
    chat_id = f"{digits}@c.us" if "@" not in phone else phone

    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["X-Api-Key"] = api_key

    # Search for an image sample to send
    image_paths = (
        glob.glob("evidence/images/*.jpg")
        + glob.glob("images/*.jpg")
        + glob.glob("evidence/*.jpg")
    )
    test_image = image_paths[0] if image_paths else None

    caption = (
        "🚨 *TEST ALERT - DROWNING DETECTION SYSTEM* 🚨\n\n"
        "✅ Your WAHA WhatsApp integration is working successfully!\n"
        "📹 Camera: Test-Camera-01\n"
        "📍 Location: Shallow End\n"
        "📊 Confidence: 94.5%\n\n"
        "This is a test notification generated by waha_test.py."
    )

    print(f"\n[3/3] Sending alert message to {chat_id}...")

    if test_image and os.path.exists(test_image):
        print(f"[INFO] Attaching snapshot: {test_image}")
        try:
            with open(test_image, "rb") as f:
                b64_data = base64.b64encode(f.read()).decode("utf-8")

            payload = {
                "session": session,
                "chatId": chat_id,
                "file": {
                    "mimetype": "image/jpeg",
                    "filename": Path(test_image).name,
                    "data": b64_data,
                },
                "caption": caption,
            }

            resp = requests.post(
                f"{base_url}/api/sendImage",
                json=payload,
                headers=headers,
                timeout=25,
            )

            if resp.status_code in (200, 201):
                res_json = resp.json()
                msg_id = res_json.get("id", "SUCCESS")
                print(f"[SUCCESS] WhatsApp alert with snapshot was sent! Message ID: {msg_id}")
                return True
            else:
                print(f"[WARN] Failed to send image (HTTP {resp.status_code}): {resp.text}")
                print("[INFO] Retrying as text message...")
        except Exception as e:
            print(f"[WARN] Error attaching image: {e}. Retrying as text message...")

    # Fallback to text message
    try:
        text_payload = {
            "session": session,
            "chatId": chat_id,
            "text": caption,
        }
        resp = requests.post(
            f"{base_url}/api/sendText",
            json=text_payload,
            headers=headers,
            timeout=15,
        )
        if resp.status_code in (200, 201):
            res_json = resp.json()
            msg_id = res_json.get("id", "SUCCESS")
            print(f"[SUCCESS] WhatsApp text alert was sent! Message ID: {msg_id}")
            return True
        else:
            print(f"[FAIL] Failed to send text message (HTTP {resp.status_code}): {resp.text}")
            return False
    except Exception as exc:
        print(f"[FAIL] Exception sending message: {exc}")
        return False


def main():
    parser = argparse.ArgumentParser(description="Test WAHA WhatsApp Integration")
    parser.add_argument("--url", default=DEFAULT_URL, help="WAHA Server URL")
    parser.add_argument("--session", default=DEFAULT_SESSION, help="WAHA Session Name")
    parser.add_argument("--to", default=DEFAULT_PHONE, help="Target phone number with country code")
    parser.add_argument("--key", default=DEFAULT_KEY, help="Optional WAHA API Key")
    parser.add_argument("--pair", default="", help="Phone number to get pairing code instead of scanning QR")

    args = parser.parse_args()

    base_url = args.url.rstrip("/")
    session = args.session
    api_key = args.key
    phone = args.to

    print("=" * 60)
    print("      WAHA WhatsApp Integration Diagnostics & Test")
    print("=" * 60)

    if args.pair:
        import re
        pair_number = re.sub(r"\D", "", args.pair)
        if pair_number.startswith("00"):
            pair_number = pair_number[2:]
        print(f"\n[*] Preparing fresh pairing session for +{pair_number}...")
        headers = {"Content-Type": "application/json"}
        if api_key:
            headers["X-Api-Key"] = api_key
        try:
            import time
            # Cleanly recreate and start session to avoid stale FAILED state
            requests.delete(f"{base_url}/api/sessions/{session}", headers=headers, timeout=5)
            time.sleep(1)
            requests.post(f"{base_url}/api/sessions", json={"name": session}, headers=headers, timeout=5)
            time.sleep(1)
            requests.post(f"{base_url}/api/sessions/{session}/start", headers=headers, timeout=5)
            time.sleep(3)

            r = requests.post(
                f"{base_url}/api/{session}/auth/request-code",
                json={"phoneNumber": pair_number},
                headers=headers,
                timeout=15,
            )
            if r.status_code in (200, 201):
                code = r.json().get("code")
                print("\n" + "=" * 40)
                print(f"   PAIRING CODE:  {code}")
                print("=" * 40)
                print("\nInstructions on your phone:")
                print("1. Open WhatsApp -> Settings -> Linked Devices -> Link a Device")
                print("2. Tap 'Link with phone number instead' at the bottom")
                print(f"3. Type this 8-character code: {code}\n")
                return
            else:
                print(f"[FAIL] Could not get code (HTTP {r.status_code}): {r.text}")
                return
        except Exception as ex:
            print(f"[FAIL] Error requesting code: {ex}")
            return

    ok, status = check_status(base_url, session, api_key)
    if not ok:
        sys.exit(1)

    if not phone:
        print("\n[PROMPT] Please enter the recipient phone number with country code")
        print("         (e.g., 919876543210 for India, 12345678901 for US):")
        try:
            phone = input("Phone Number: ").strip()
        except EOFError:
            phone = ""

    if not phone:
        print("[FAIL] No phone number specified. Exiting.")
        sys.exit(1)

    sent = send_test_alert(base_url, session, phone, api_key)
    if sent:
        print("\n[SUCCESS] WhatsApp test passed successfully!")
    else:
        print("\n[FAIL] Failed to send WhatsApp message. Please check the logs above.")


if __name__ == "__main__":
    main()
